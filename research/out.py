    w=csv.writer(f); w.writerow(['代码','名称','行业','社保持有期数','ROE2024','ROE2025','ROE2026前三季','净利同比%','营收同比%','PE_TTM','市值亿','社保持仓亿','社保变动','年内涨跌%','综合分'])
