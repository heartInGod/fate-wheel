    rows.append([x['code'],x['name'].replace(' ',''),x['ind'],x['n'],x['roe24'],x['roe25'],x['roe9'],round(x['np'],1),round(x['rev'],1),x['pe'],round(x['cap']),round(x['val'],2),x['cha'],x['y'],x['score']])
